// Generates packages/bittune-runtime/src/harness/cloud-contracts.ts from the
// Local contract mirror (contracts/cloud/openapi.yaml) using the pinned
// openapi-typescript version. The committed banner line is stripped before
// comparison, so --check only fails on real type drift.
//
//   node scripts/generate-cloud-contracts.mjs          # regenerate
//   node scripts/generate-cloud-contracts.mjs --check  # fail on drift
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const BANNER = `// @generated by scripts/generate-cloud-contracts.mjs from contracts/cloud/openapi.yaml — DO NOT EDIT.\n`;
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mirror = join(repoRoot, "contracts", "cloud", "openapi.yaml");
const target = join(repoRoot, "packages", "bittune-runtime", "src", "harness", "cloud-contracts.ts");
const checkMode = process.argv.includes("--check");

if (!existsSync(mirror)) {
	console.error(`mirror missing: ${mirror}`);
	process.exit(1);
}

function generate() {
	const work = mkdtempSync(join(tmpdir(), "cloud-contracts-"));
	const draft = join(work, "draft.ts");
	try {
		// Invoke the pinned CLI through node directly: npx is a .cmd shim on
		// Windows and fails under spawn from a plain node script.
		const cli = join(repoRoot, "node_modules", "openapi-typescript", "bin", "cli.js");
		execFileSync(process.execPath, [cli, mirror, "--output", draft], {
			stdio: "pipe",
			encoding: "utf8",
		});
		return readFileSync(draft, "utf8");
	} finally {
		rmSync(work, { recursive: true, force: true });
	}
}

const generated = generate();
const committed = existsSync(target) ? readFileSync(target, "utf8") : null;

if (checkMode) {
	if (committed === null) {
		console.error(`check:cloud-contract FAILED: generated file missing: ${target}`);
		process.exit(1);
	}
	const normalized = committed.startsWith(BANNER) ? committed.slice(BANNER.length) : committed;
	if (generated !== normalized) {
		console.error(
			"check:cloud-contract FAILED: cloud-contracts.ts is out of date; run: npm run generate:cloud-contracts",
		);
		process.exit(1);
	}
	console.log("check:cloud-contract OK: cloud-contracts.ts is up to date");
} else {
	writeFileSync(target, BANNER + generated);
	console.log(`wrote ${target}`);
}